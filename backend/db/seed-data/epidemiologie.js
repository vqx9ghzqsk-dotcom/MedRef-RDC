/** Fréquence d'une fiche : 'tres_frequente' | 'frequente' | 'peu_frequente' | 'rare'. */
function frequenceDe(slug) {
  if (TRES_FREQUENTES.includes(slug)) return 'tres_frequente';
  if (FREQUENTES.includes(slug)) return 'frequente';
  if (RARES.includes(slug)) return 'rare';
  return 'peu_frequente';
}

function saisonDe(slug) {
  return Object.keys(SAISONS).find((s) => SAISONS[s].test(slug)) || null;
}

