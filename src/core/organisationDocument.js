export function normaliserTerme(value) {
  return String(value || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[’'`]/g, ' ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

function classer(pathologie, groupes) {
  const texte = normaliserTerme(`${pathologie.nom} ${pathologie.slug}`);
  let meilleur = null;
  let scoreMax = 0;
  for (const item of groupes) {
    const score = item.mots.reduce((max, mot) => {
      const terme = normaliserTerme(mot);
      return terme && texte.includes(terme) ? Math.max(max, terme.length) : max;
    }, 0);
    if (score > scoreMax) {
      meilleur = item.nom;
      scoreMax = score;
    }
  }
  return meilleur;
}

const SECTIONS_EXPLICITES_PAR_PATHOLOGIE = new Map([
  ['dyskaliemies', 'nephrologie-troubles-hydro-electrolytiques'],
  ['hyponatremie', 'nephrologie-troubles-hydro-electrolytiques'],
]);

function sectionContientPathologie(pathologie, sectionDocument) {
  const sectionForcee = SECTIONS_EXPLICITES_PAR_PATHOLOGIE.get(pathologie.slug);
  return sectionForcee
    ? sectionDocument.slug === sectionForcee
    : sectionDocument.sources.includes(pathologie.specialite_slug);
}

function grouper(sectionDocument, pathologies) {
  const groupes = sectionDocument.groupes.map((item) => ({
    slug: normaliserTerme(item.nom).replace(/\s+/g, '-'),
    nom: item.nom,
    pathologies: [],
  }));
  const groupeParNom = new Map(groupes.map((item) => [item.nom, item]));
  const autres = [];

  for (const pathologie of pathologies) {
    const nomGroupe = classer(pathologie, sectionDocument.groupes);
    const destination = nomGroupe ? groupeParNom.get(nomGroupe) : null;
    if (destination) destination.pathologies.push(pathologie);
    else autres.push(pathologie);
  }

  const trier = (liste) => liste.sort((a, b) => a.nom.localeCompare(b.nom, 'fr'));
  for (const item of groupes) trier(item.pathologies);
  if (autres.length) {
    groupes.push({
      slug: 'autres-fiches-conservees',
      nom: 'Autres fiches conservées',
      pathologies: trier(autres),
    });
  }
  return groupes;
}

export function trouverDepartementDocument(slug) {
  return ORGANISATION_DOCUMENT.find((item) => item.slug === slug) || null;
}

export function trouverSectionDocument(departementSlug, sectionSlug) {
  const departement = trouverDepartementDocument(departementSlug);
  return departement?.sections.find((item) => item.slug === sectionSlug) || null;
}

export function trouverSectionSpecialite(specialiteSlug) {
  for (const departement of ORGANISATION_DOCUMENT) {
    const section = departement.sections.find((item) => item.sources.includes(specialiteSlug));
    if (section) return { departement, section };
  }
  return null;
}

export function organiserDepartement(departementSlug, pathologies) {
  const departement = trouverDepartementDocument(departementSlug);
  if (!departement) return null;

  const dejaAffectees = new Set();
  const sections = departement.sections.map((item) => {
    const liste = pathologies.filter(
      (pathologie) =>
        pathologie.departement_slug === departementSlug && sectionContientPathologie(pathologie, item),
    );
    for (const pathologie of liste) dejaAffectees.add(pathologie.slug);
    return {
      ...item,
      nb_pathologies: liste.length,
      groupes: grouper(item, liste),
    };
  });
  const autres = pathologies
    .filter(
      (pathologie) =>
        pathologie.departement_slug === departementSlug &&
        !dejaAffectees.has(pathologie.slug) &&
        !(departement.horsDocument || []).includes(pathologie.specialite_slug),
    )
    .sort((a, b) => a.nom.localeCompare(b.nom, 'fr'));
  const horsDocument = pathologies
    .filter(
      (pathologie) =>
        pathologie.departement_slug === departementSlug &&
        (departement.horsDocument || []).includes(pathologie.specialite_slug),
    )
    .sort((a, b) => a.nom.localeCompare(b.nom, 'fr'));

  return { departement, sections, autres, horsDocument };
}

export function organiserSectionDocument(departementSlug, sectionSlug, pathologies) {
  const departement = trouverDepartementDocument(departementSlug);
  const sectionDocument = trouverSectionDocument(departementSlug, sectionSlug);
  if (!departement || !sectionDocument) return null;
  const liste = pathologies.filter(
    (pathologie) =>
      pathologie.departement_slug === departementSlug &&
      sectionContientPathologie(pathologie, sectionDocument),
  );
  return {
    departement,
    section: sectionDocument,
    nb_pathologies: liste.length,
    groupes: grouper(sectionDocument, liste),
  };
}

export function organiserGroupeDocument(departementSlug, sectionSlug, groupSlug, pathologies) {
  const organisation = organiserSectionDocument(departementSlug, sectionSlug, pathologies);
  if (!organisation) return null;
  const groupe = organisation.groupes.find((item) => item.slug === groupSlug);
  if (!groupe) return null;
  return {
    departement: organisation.departement,
    section: organisation.section,
    groupe,
    nb_pathologies: groupe.pathologies.length,
  };
}
